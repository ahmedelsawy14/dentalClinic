export function getServiceBySlug(slug) {
  if (!slug) return undefined;
  const normalizedSlug = slug.toString().trim().toLowerCase();
  return services.find((item) => item.slug === normalizedSlug);
}

export function getAllServices() {
  return services;
}

export function getRelatedServices(currentSlug, limit = 2) {
  const service = getServiceBySlug(currentSlug);

  if (!service) {
    return services.slice(0, limit);
  }

  const relatedServices = services.filter(
    (item) => item.slug !== currentSlug && (service.related || []).includes(item.slug),
  );

  if (relatedServices.length >= limit) {
    return relatedServices.slice(0, limit);
  }

  const fallbacks = services.filter(
    (item) =>
      item.slug !== currentSlug && !relatedServices.some((related) => related.slug === item.slug),
  );

  return [...relatedServices, ...fallbacks].slice(0, limit);
}

export default services;
